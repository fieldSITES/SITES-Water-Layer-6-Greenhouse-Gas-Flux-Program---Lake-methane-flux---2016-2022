dfTw_S['Lake2'] = dfTw_S['Lake'].copy()
dfTw_S.set_index('Lake', inplace = True) # Lake name as index needed for loop by lake?

corrTinit = []
corrTend = []
dfvardz = []
BrPardz = []
dfTAMi_app =[]
# Make dfs with init and end water temp.
